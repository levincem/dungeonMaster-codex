const FRONT_WALL_REFERENCE_WIDTH = 160;
const FRONT_WALL_REFERENCE_HEIGHT = 111;
const STAIRS_UP_FRONT2_WIDTH = 100;
const STAIRS_UP_FRONT2_HEIGHT = 63;
const STAIRS_DOWN_FRONT2_WIDTH = 98;
const STAIRS_DOWN_FRONT2_HEIGHT = 61;

export const ORIGINAL_FRONT_WALL_REFERENCE_WIDTH = FRONT_WALL_REFERENCE_WIDTH;
export const ORIGINAL_FRONT_WALL_REFERENCE_HEIGHT = FRONT_WALL_REFERENCE_HEIGHT;
export const ORIGINAL_STAIRS_UP_FRONT2_WIDTH = STAIRS_UP_FRONT2_WIDTH;
export const ORIGINAL_STAIRS_UP_FRONT2_HEIGHT = STAIRS_UP_FRONT2_HEIGHT;
export const ORIGINAL_STAIRS_DOWN_FRONT2_WIDTH = STAIRS_DOWN_FRONT2_WIDTH;
export const ORIGINAL_STAIRS_DOWN_FRONT2_HEIGHT = STAIRS_DOWN_FRONT2_HEIGHT;

export function getOriginalStairsUpFrontWidthRatio(): number {
    return STAIRS_UP_FRONT2_WIDTH / FRONT_WALL_REFERENCE_WIDTH;
}

export function getOriginalStairsUpFrontHeightRatio(): number {
    return STAIRS_UP_FRONT2_HEIGHT / FRONT_WALL_REFERENCE_HEIGHT;
}

export function getOriginalStairsDownFrontWidthRatio(): number {
    return STAIRS_DOWN_FRONT2_WIDTH / FRONT_WALL_REFERENCE_WIDTH;
}

export function getOriginalStairsDownFrontHeightRatio(): number {
    return STAIRS_DOWN_FRONT2_HEIGHT / FRONT_WALL_REFERENCE_HEIGHT;
}
